-- Schema for the Postgres backend. Safe to run more than once.
-- Docker runs it on the very first start of an empty volume (docker-entrypoint-initdb.d),
-- and the app runs it again on every start, so a fresh clone needs no manual step.
CREATE TABLE IF NOT EXISTS tasks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      TEXT        NOT NULL CHECK (length(btrim(title)) > 0),
    done       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tasks_done ON tasks (done);
