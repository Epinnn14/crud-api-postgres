"""The contract every storage backend implements. Routes only ever talk to this interface."""
from __future__ import annotations

from typing import Protocol

SEED = [
    ("Read the A1 brief", True),
    ("Build the CRUD API", False),
    ("Publish to GitHub", False),
]

SORTS = ("id", "title", "created_at")


class TaskRepository(Protocol):
    def init(self) -> None: ...
    def list_tasks(self, done: bool | None = None, search: str | None = None, sort: str = "id",
                   limit: int | None = None, offset: int = 0) -> list[dict]: ...
    def get_task(self, task_id: int) -> dict | None: ...
    def create_task(self, title: str) -> dict: ...
    def update_task(self, task_id: int, title: str | None, done: bool | None) -> dict | None: ...
    def delete_task(self, task_id: int) -> bool: ...
    def stats(self) -> dict: ...
    def reset(self) -> list[dict]: ...
